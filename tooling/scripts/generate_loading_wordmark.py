#!/usr/bin/env python3
"""Generate the outlined loading-screen wordmark as SVG glyph geometry.

The title follows the approved 60-degree arc above the Confluence orb.  Every
letter is converted from Alfa Slab One to paths so Unity never depends on a
runtime font, font fallback, or TextMeshPro warping for the brand mark.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from pathlib import Path
from xml.sax.saxutils import escape

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[2]
FONT_PATH = ROOT / "unity/Assets/Art/Fonts/AlfaSlabOne-Regular.ttf"
OUTPUT_PATH = (
    ROOT / "unity/Assets/Art/UI/Loading_Wordmark_KingdomOfBadIdeas.svg"
)

TEXT = "KINGDOM OF BAD IDEAS"
CANVAS_WIDTH = 1600
CANVAS_HEIGHT = 330
ARC_DEGREES = 60.0
ARC_LENGTH = 1460.0
BASELINE_Y = 108.0
TRACKING_UNITS = 42.0


@dataclass(frozen=True)
class Letter:
    path: str
    x: float
    y: float
    angle: float
    scale: float
    advance: float
    fill: str


def glyph_factor(index: int) -> float:
    # Keep the small connective "OF" from competing with the two comic nouns.
    return 0.70 if index in (8, 9) else 1.0


def build_letters(font: TTFont) -> list[Letter]:
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    metrics = font["hmtx"].metrics
    glyph_rows: list[tuple[str, float, float, str]] = []

    total_units = 0.0
    for index, character in enumerate(TEXT):
        glyph_name = cmap[ord(character)]
        factor = glyph_factor(index)
        advance = metrics[glyph_name][0] * factor
        path = ""
        if character != " ":
            pen = SVGPathPen(glyph_set)
            glyph_set[glyph_name].draw(pen)
            path = pen.getCommands()
        glyph_rows.append((path, advance, factor, character))
        total_units += advance

    total_units += TRACKING_UNITS * (len(TEXT) - 1)
    base_scale = ARC_LENGTH / total_units
    radius = ARC_LENGTH / math.radians(ARC_DEGREES)

    cursor = -total_units / 2.0
    letters: list[Letter] = []
    for index, (path, advance, factor, character) in enumerate(glyph_rows):
        center_units = cursor + advance / 2.0
        arc_distance = center_units * base_scale
        theta = arc_distance / radius
        x = CANVAS_WIDTH / 2.0 + radius * math.sin(theta)
        y = BASELINE_Y + radius * (1.0 - math.cos(theta))
        letters.append(
            Letter(
                path=path,
                x=x,
                y=y,
                angle=math.degrees(theta),
                scale=base_scale * factor,
                advance=metrics[cmap[ord(character)]][0],
                fill="#e7aa52" if index in (8, 9) else "#f3dca8",
            )
        )
        cursor += advance + (TRACKING_UNITS if index < len(TEXT) - 1 else 0.0)

    return letters


def glyph_path(letter: Letter, *, dx: float = 0.0, dy: float = 0.0) -> str:
    if not letter.path:
        return ""
    transform = (
        f"translate({letter.x + dx:.3f} {letter.y + dy:.3f}) "
        f"rotate({letter.angle:.3f}) "
        f"scale({letter.scale:.6f} {-letter.scale:.6f}) "
        f"translate({-letter.advance / 2.0:.3f} 0)"
    )
    return f'<path d="{escape(letter.path)}" transform="{transform}"/>'


def layer(
    letters: list[Letter],
    *,
    name: str,
    fill: str | None,
    stroke: str,
    stroke_width: int,
    dx: float = 0.0,
    dy: float = 0.0,
) -> str:
    paths = []
    for letter in letters:
        path = glyph_path(letter, dx=dx, dy=dy)
        if path:
            letter_fill = letter.fill if fill is None else fill
            paths.append(
                path.replace(
                    "/>",
                    f' fill="{letter_fill}" stroke="{stroke}" '
                    f'stroke-width="{stroke_width}" stroke-linejoin="round"/>',
                )
            )
    return f'<g id="{name}">\n    ' + "\n    ".join(paths) + "\n  </g>"


def render_svg(letters: list[Letter]) -> str:
    # The crooked little crown is intentionally imperfect.  It occupies the
    # visual pause above "OF" without borrowing space from the orb below.
    crown = """<g id="crooked-crown" transform="translate(799 35) rotate(-7)">
    <path d="M-59 22 L-45 -27 L-15 4 L5 -35 L27 2 L55 -23 L61 27 Z"
          fill="#20120d" stroke="#20120d" stroke-width="15" stroke-linejoin="round"/>
    <path d="M-57 17 L-43 -24 L-14 8 L6 -31 L28 6 L53 -19 L58 23 Z"
          fill="#e3a84c" stroke="#8c3c1d" stroke-width="6" stroke-linejoin="round"/>
    <path d="M-50 17 Q0 28 51 18" fill="none" stroke="#f4d690" stroke-width="5"
          stroke-linecap="round"/>
  </g>"""

    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tooling/scripts/generate_loading_wordmark.py. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS_WIDTH} {CANVAS_HEIGHT}"
     width="{CANVAS_WIDTH}" height="{CANVAS_HEIGHT}" role="img"
     aria-label="Kingdom of Bad Ideas">
  {layer(letters, name="charred-shadow", fill="#1b100c", stroke="#1b100c", stroke_width=112, dx=7, dy=9)}
  {layer(letters, name="dark-keyline", fill="#703019", stroke="#1b100c", stroke_width=76)}
  {layer(letters, name="parchment-face", fill=None, stroke="#9a431f", stroke_width=27)}
  {crown}
</svg>
"""


def main() -> None:
    font = TTFont(FONT_PATH)
    OUTPUT_PATH.write_text(render_svg(build_letters(font)), encoding="utf-8", newline="\n")
    print(OUTPUT_PATH)


if __name__ == "__main__":
    main()
