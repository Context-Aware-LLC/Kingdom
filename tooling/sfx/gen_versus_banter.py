#!/usr/bin/env python3
"""Write the versus banter table Unity plays from, out of voice-lines.json.

    python tooling/sfx/gen_versus_banter.py           # rewrite the C# table
    python tooling/sfx/gen_versus_banter.py --check   # exit 1 if it is stale

voice-lines.json is the script and the cast; Unity never reads it. The captions and the
order of each exchange have to reach the client, so this writes them into
unity/Assets/Scripts/Presentation/VersusBanterLines.cs. Rerun it after any change to a
vs_<class> line or to _versus_openers, or the captions say one thing and the clip another.
"""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
LINES = pathlib.Path(__file__).resolve().parent / "voice-lines.json"
OUT = ROOT / "unity" / "Assets" / "Scripts" / "Presentation" / "VersusBanterLines.cs"


def cs_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(data):
    voices = data["voices"]
    classes = list(voices)
    openers = {tuple(p) for p in data["_versus_openers"]}

    for a in classes:
        for b in classes:
            if not voices[a]["lines"].get("vs_" + b.lower()):
                sys.exit("%s has no vs_%s line" % (a, b.lower()))
            if a < b and ((a, b) in openers) == ((b, a) in openers):
                sys.exit("%s/%s needs exactly one entry in _versus_openers" % (a, b))

    out = [
        "// GENERATED by tooling/sfx/gen_versus_banter.py from tooling/sfx/voice-lines.json.",
        "// Do not edit by hand: change the json and rerun the script.",
        "using System.Collections.Generic;",
        "using Kingdom.Core.Contracts;",
        "",
        "namespace Kingdom.Presentation",
        "{",
        "    internal static class VersusBanterLines",
        "    {",
        "        public static string HeroName(CardClass c) => c switch",
        "        {",
    ]
    for c in classes:
        out.append("            CardClass.%s => %s," % (c, cs_string(voices[c]["hero"])))
    out += [
        '            _ => "",',
        "        };",
        "",
        "        /// <summary>(speaker, the hero spoken to) -> the line. A mirror keys a class to itself.</summary>",
        "        public static readonly IReadOnlyDictionary<(CardClass, CardClass), string> Lines =",
        "            new Dictionary<(CardClass, CardClass), string>",
        "            {",
    ]
    for a in classes:
        for b in classes:
            out.append("                [(CardClass.%s, CardClass.%s)] = %s," % (
                a, b, cs_string(voices[a]["lines"]["vs_" + b.lower()][0])))
    out += [
        "            };",
        "",
        "        /// <summary>The hero who speaks first in each pair. The other answers, whichever seat",
        "        /// is local, because a reply only lands after its own opener.</summary>",
        "        public static readonly HashSet<(CardClass, CardClass)> Openers = new()",
        "        {",
    ]
    for a, b in data["_versus_openers"]:
        out.append("            (CardClass.%s, CardClass.%s)," % (a, b))
    out += ["        };", "    }", "}", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the C# table is stale")
    args = ap.parse_args()
    text = render(json.loads(LINES.read_text(encoding="utf-8")))
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("%s is stale; rerun tooling/sfx/gen_versus_banter.py" % OUT.relative_to(ROOT))
            return 1
        print("up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
