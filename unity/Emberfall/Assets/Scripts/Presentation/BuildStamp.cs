using UnityEngine;

namespace Emberfall.Presentation
{
    /// <summary>
    /// #195 — what build a tester is looking at.
    ///
    /// <para>Sam: <i>"We need some way for testers to know what version they are testing in order to
    /// provide us with better feedback. Currently the main menu displays 'M1 - Vertical Slice'.
    /// Replace this with proper versioning numbers. I suppose a long ordinal system that github
    /// actions auto-increments on merge would be best."</i></para>
    ///
    /// <para><b>THE ORDINAL IS <c>git rev-list --count HEAD</c>, NOT A COUNTER CI KEEPS.</b> It
    /// increments on every merge exactly as asked, and it is strictly better than a stored number:
    /// nothing has to be committed back, two merges landing at once cannot race it, and it is
    /// reproducible from any checkout at any commit — including a bisect, where a CI-maintained
    /// counter would report whatever it happened to hold. The short SHA rides along, because an
    /// ordinal alone cannot tell you which branch a tester's build came off.</para>
    ///
    /// <para><b>Written at build time, read here.</b> <c>BuildStampWriter</c> (Editor) emits
    /// <c>Assets/Resources/build-stamp.txt</c> in <c>IPreprocessBuildWithReport</c> so the value is
    /// baked into the player. It is generated output and gitignored — regenerated by every build,
    /// never committed, so it cannot drift from the commit it claims to describe.</para>
    ///
    /// <para><b>In the Editor there is no stamp</b>, because no build ran. Play mode reports
    /// <c>editor</c> rather than the last APK's number, which would be a lie about what is running.
    /// That is deliberate: a wrong build id is worse than an obvious absence, since the entire point
    /// is that a tester's report can be trusted to name their build.</para>
    /// </summary>
    public static class BuildStamp
    {
        /// <summary>Resources path, no extension — must match BuildStampWriter's output.</summary>
        public const string ResourceName = "build-stamp";

        /// <summary>Field separator. Chosen because none of the four fields can contain it: a
        /// version is dotted digits, the ordinal is digits, the SHA is hex, and the timestamp is
        /// ISO-8601 with no spaces.</summary>
        public const char Separator = '|';

        private static string _display;

        /// <summary>
        /// What to show a tester, e.g. <c>v1.0 · r1127 · 6db4f123</c>. Never null and never empty —
        /// a footer that renders nothing tells a tester less than one that says <c>editor</c>.
        /// </summary>
        public static string Display
        {
            get
            {
                if (_display != null) return _display;
                _display = Build();
                return _display;
            }
        }

        private static string Build()
        {
            var asset = Resources.Load<TextAsset>(ResourceName);
            if (asset == null || string.IsNullOrWhiteSpace(asset.text))
            {
                // No stamp means no build ran — the Editor, or a player built before this landed.
                // Application.version still carries PlayerSettings.bundleVersion, which is real.
                return "v" + Application.version + " · editor";
            }

            string[] parts = asset.text.Trim().Split(Separator);
            if (parts.Length < 3)
            {
                Debug.LogWarning("[BuildStamp] '" + ResourceName + "' has "
                    + parts.Length + " field(s), expected at least 3 (version|revision|sha). "
                    + "Showing the raw text rather than guessing at it.");
                return asset.text.Trim();
            }

            return "v" + parts[0] + " · r" + parts[1] + " · " + parts[2];
        }
    }
}
