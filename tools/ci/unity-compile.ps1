# Fast, Editor-free compile gate for the assemblies ONLY Unity builds.
#
# WHY THIS EXISTS. The GitHub gates run ubuntu-latest and license-free, so Stages 7-8 are
# informational (ci-gates.md §7 Q1) and NOTHING gates the Unity-side C#. The deterministic core
# is covered because it is tested through dotnet, but Emberfall.Presentation, .Editor, .AI,
# .Data and .Session are compiled by Unity and by nothing else. Code can be green on every
# stage and still fail to compile the moment the Editor opens.
#
# That happened twice on 2026-08-06:
#   * InternalsVisibleTo declared in a .csproj is invisible to Unity, which builds from the
#     .asmdef - so `internal` members read across assemblies compiled under dotnet and not
#     under Unity, taking every downstream assembly with them.
#   * The NOR-31 refactor left three presentation call sites on retired APIs
#     (_state/_selectedId, CardDefinition.CardText, effects:/EffectDef).
# Both surfaced only as Unity Safe Mode plus a Burst "Failed to resolve assembly" - which point
# nowhere near the cause.
#
# WHY NOT unity-verify.ps1. That is the fuller gate and still the one to run before a release:
# it drives a real Editor and runs HeadlessVerify's self-checks. But it costs a domain reload,
# and the Editor is a SINGLE-WRITER resource - if one is already open, this is the check you can
# actually run. This one needs no Editor, no license, and no domain reload; it needs only the
# Unity DLLs already on disk, because Unity's generated .csproj files reference them directly.
#
# WHAT IT DOES NOT DO. It compiles; it does not run. A green result means the C# is consistent
# with the core, not that anything behaves. It also cannot run on a license-free CI runner: the
# generated .csproj files hardcode this machine's Unity install path. Local/self-hosted only.
#
# Usage: pwsh tools/ci/unity-compile.ps1
#        pwsh tools/ci/unity-compile.ps1 -Configuration Release
[CmdletBinding()]
param(
    [string]$Configuration = 'Debug'
)

$ErrorActionPreference = 'Stop'

# Path segments are joined via Path.Combine, never with literal '\'. A backslash is a legal
# FILENAME character on Linux, so 'unity\Emberfall' there is not a path - it is a single odd
# filename that simply does not exist, and this script would fail below with "Unity project not
# found" as though the checkout were broken. Same trap that created literal 'C:\pw\...'
# directories in the agents box.
$REPO_ROOT = [System.IO.Path]::GetFullPath([System.IO.Path]::Combine($PSScriptRoot, '..', '..'))
$PROJECT   = [System.IO.Path]::Combine($REPO_ROOT, 'unity', 'Emberfall')

if (-not (Test-Path $PROJECT)) {
    Write-Error "Unity project not found at '$PROJECT'."
    exit 1
}

# OUR assemblies only. The Unity.* and Assembly-CSharp projects are package/scaffold output and
# are not ours to gate; failing on somebody else's package would make this gate untrustworthy
# and it would stop being run.
$projects = Get-ChildItem -Path $PROJECT -Filter 'Emberfall.*.csproj' -File |
            Sort-Object Name

if ($projects.Count -eq 0) {
    # The remedy here used to name tools/ci/unity-verify.ps1, which does NOT generate these and
    # cannot. Verified 2026-08-15 on a fresh clone: a fully green headless run (Library built to
    # 3.6 GB, 8/8 checks PASS) still left 0 csproj and 0 sln, and -executeMethod
    # UnityEditor.SyncVS.SyncSolution resolved, ran in 0.132 ms and produced nothing. Project
    # generation is delegated to a CodeEditor package (com.unity.ide.visualstudio / rider), and a
    # headless Editor has none registered - so no batchmode invocation produces them.
    Write-Error @"
No Emberfall.*.csproj found in '$PROJECT'.

These are generated by the Unity Editor's code-editor integration, NOT by any script in this repo.
Nothing headless generates them - unity-verify.ps1 does not, and neither does -executeMethod
UnityEditor.SyncVS.SyncSolution, because project generation needs a registered external editor.

To get them: open the project in the Editor once with VS / VS Code / Rider set under
Edit > Preferences > External Tools, then use 'Regenerate project files' there.

If you cannot get the Editor - it is single-writer, so someone else may have it - do not wait for
it and do not try to copy csprojs from another machine or worktree (they hardcode absolute Unity
and checkout paths). Run the full gate in WSL instead, which needs none of this:

    pwsh tools/ci/unity-gate-wsl.ps1
"@
    # RETIREMENT TRIGGER: if headless csproj generation is ever solved, the message above and the
    # "WHY NOT JUST COPY THE CSPROJS OVER" section of unity-gate-wsl.ps1 both stop being true.
    exit 1
}

# The generated projects reference Unity's own DLLs by absolute path. If Unity is installed
# somewhere else, every build fails with hundreds of type-not-found errors that look like real
# code breakage. Say so up front instead.
$sample  = Select-String -Path $projects[0].FullName -Pattern '<HintPath>(.+?UnityEngine\.dll)</HintPath>' |
           Select-Object -First 1
if ($sample) {
    $hint = $sample.Matches[0].Groups[1].Value
    if (-not (Test-Path $hint)) {
        Write-Warning @"
This project's generated .csproj files point at a Unity install that is not on this machine:
  $hint
Every build below will fail with missing-type errors that are NOT code defects. Reopen the
project in your local Unity to regenerate the .csproj files first.
"@
    }
}

Write-Host "Compiling $($projects.Count) Emberfall assemblies ($Configuration) - no Editor, no license." -ForegroundColor Cyan
Write-Host ''

$failed = [System.Collections.Generic.List[string]]::new()

foreach ($proj in $projects) {
    $name = [System.IO.Path]::GetFileNameWithoutExtension($proj.Name)
    Write-Host ("  {0,-30} " -f $name) -NoNewline

    $output = & dotnet build $proj.FullName -c $Configuration -v q --nologo 2>&1

    if ($LASTEXITCODE -eq 0) {
        Write-Host 'OK' -ForegroundColor Green
        continue
    }

    Write-Host 'FAILED' -ForegroundColor Red
    $failed.Add($name)

    # One line per distinct error. A single broken API can produce the same error in dozens of
    # places, and an unfiltered dump buries the one line that matters.
    $errors = $output |
        Select-String -Pattern '([^\\/]+\.cs\(\d+,\d+\)): (error [A-Z]+\d+: .+?)(?: \[|$)' |
        ForEach-Object { "$($_.Matches[0].Groups[1].Value): $($_.Matches[0].Groups[2].Value)" } |
        Select-Object -Unique

    if (-not $errors) { $errors = @('(no CS error parsed - run dotnet build on this project directly)') }
    foreach ($e in $errors) { Write-Host "      $e" -ForegroundColor DarkYellow }
}

Write-Host ''

if ($failed.Count -gt 0) {
    Write-Host "FAIL - $($failed.Count) of $($projects.Count) assemblies do not compile: $($failed -join ', ')" -ForegroundColor Red
    Write-Host 'Unity will drop into Safe Mode with these. Fix before pushing.' -ForegroundColor Red
    exit 1
}

Write-Host "PASS - all $($projects.Count) Emberfall assemblies compile." -ForegroundColor Green
exit 0
